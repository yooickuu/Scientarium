create function scientarium_private.sync_auth_user() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.email is null then return new; end if;
 insert into public.profiles(auth_id,email,full_name)
 values(new.id,lower(new.email),left(coalesce(nullif(btrim(new.raw_user_meta_data->>'full_name'),''),split_part(new.email,'@',1)),150))
 on conflict(auth_id) do update set email=excluded.email;
 return new;
end $$;
revoke all on function scientarium_private.sync_auth_user() from public,anon,authenticated;
create trigger scientarium_auth_user after insert or update of email on auth.users for each row execute function scientarium_private.sync_auth_user();
-- Covers accounts manually created before the migration; metadata never grants roles.
insert into public.profiles(auth_id,email,full_name)
 select id,lower(email),left(coalesce(nullif(btrim(raw_user_meta_data->>'full_name'),''),split_part(email,'@',1)),150)
 from auth.users where email is not null on conflict(auth_id) do nothing;

