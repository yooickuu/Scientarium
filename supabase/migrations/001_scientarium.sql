create function public.set_user_role(target_email text,new_role text) returns jsonb language plpgsql security definer set search_path='' as $$
declare target public.profiles;
begin
 -- Serialize role changes; authorization is checked after obtaining the lock.
 perform pg_advisory_xact_lock(648201);
 if scientarium_private.my_role() is distinct from 'admin' then raise exception 'forbidden'; end if;
 if new_role is null or new_role not in ('user','moderator','admin') then raise exception 'invalidInput'; end if;
 select * into target from public.profiles where email=lower(btrim(target_email)) and is_active for update;
 if not found then raise exception 'notFound'; end if;
 if target.is_owner and new_role<>'admin' then raise exception 'ownerProtected'; end if;
 if target.role='admin' and new_role<>'admin' and (select count(*) from public.profiles where role='admin' and is_active)<=1 then raise exception 'ownerProtected'; end if;
 update public.profiles set role=new_role where id=target.id;
 return jsonb_build_object('ok',true);
end $$;

create function scientarium_private.valid_image(value text,max_length integer) returns boolean language plpgsql immutable set search_path='' as $$
declare bytes bytea; mime text;
begin
 if value='' then return true; end if;
 if value is null or length(value)>max_length or value !~ '^data:image/(jpeg|png|webp);base64,[A-Za-z0-9+/]+={0,2}$' then return false; end if;
 mime=split_part(split_part(value,';',1),'/',2); bytes=decode(split_part(value,',',2),'base64');
 return case mime when 'jpeg' then substring(bytes from 1 for 3)=decode('ffd8ff','hex')
 when 'png' then substring(bytes from 1 for 8)=decode('89504e470d0a1a0a','hex')
 when 'webp' then substring(bytes from 1 for 4)=decode('52494646','hex') and substring(bytes from 9 for 4)=decode('57454250','hex') else false end;
exception when others then return false;
end $$;
create function scientarium_private.valid_url(value text) returns boolean language sql immutable set search_path='' as $$
 select value='' or (length(value)<=2000 and value ~ '^https?://[^/@[:space:]\\]+([/?#][^[:space:]\\]*)?$')
$$;
revoke all on function scientarium_private.valid_image(text,integer),scientarium_private.valid_url(text) from public,anon,authenticated;

create function public.update_profile(payload jsonb) returns jsonb language plpgsql security definer set search_path='' as $$
declare current_profile public.profiles; new_nickname text; item record;
begin
 select * into current_profile from public.profiles where id=scientarium_private.my_id() for update;
 if not found then raise exception 'loginRequired'; end if;
 if jsonb_typeof(payload) is distinct from 'object' then raise exception 'invalidInput'; end if;
 for item in select key,value from jsonb_each(payload) where key in ('full_name','university','specialty','nickname','avatar_url','account_category') loop
  if jsonb_typeof(item.value)<>'string' then raise exception 'invalidInput'; end if;
 end loop;
 if payload ? 'nickname' then
  new_nickname=nullif(lower(btrim(payload->>'nickname')),'');
  if new_nickname is distinct from current_profile.nickname then
   if new_nickname is null or new_nickname !~ '^[a-z][a-z0-9_]{2,23}$' then raise exception 'nicknameRules'; end if;
   if current_profile.nickname_changed_at>now()-interval '30 days' then raise exception 'nicknameCooldown'; end if;
   if exists(select 1 from public.profiles where nickname=new_nickname and id<>current_profile.id) then raise exception 'nicknameTaken'; end if;
   current_profile.nickname_changed_at=now(); current_profile.nickname=new_nickname;
  end if;
 end if;
 if payload ? 'avatar_url' and not scientarium_private.valid_image(payload->>'avatar_url',400000) then raise exception 'imageError'; end if;
 if payload ? 'full_name' and length(btrim(payload->>'full_name'))=0 then raise exception 'invalidInput'; end if;
 update public.profiles set
 full_name=coalesce(btrim(payload->>'full_name'),full_name), university=coalesce(btrim(payload->>'university'),university),
 specialty=coalesce(btrim(payload->>'specialty'),specialty), account_category=coalesce(payload->>'account_category',account_category),
 avatar_url=coalesce(payload->>'avatar_url',avatar_url),nickname=current_profile.nickname,nickname_changed_at=current_profile.nickname_changed_at
 where id=current_profile.id;
 return public.get_my_profile();
exception when unique_violation then raise exception 'nicknameTaken'; when check_violation then raise exception 'invalidInput';
end $$;

create function public.save_university(university_id bigint,payload jsonb) returns jsonb language plpgsql security definer set search_path='' as $$
declare result public.universities; item record;
begin
 if scientarium_private.my_role() is distinct from 'admin' then raise exception 'forbidden'; end if;
 if jsonb_typeof(payload) is distinct from 'object' then raise exception 'invalidInput'; end if;
 for item in select key,value from jsonb_each(payload) where key in ('name','name_kk','name_en','country','city','website','description','relationship') loop
  if jsonb_typeof(item.value)<>'string' then raise exception 'invalidInput'; end if;
 end loop;
 if not scientarium_private.valid_url(coalesce(payload->>'website','')) then raise exception 'invalidInput'; end if;
 if university_id is null then
  insert into public.universities(name,name_kk,name_en,country,city,website,description,relationship,is_active)
  values(btrim(payload->>'name'),coalesce(payload->>'name_kk',''),coalesce(payload->>'name_en',''),coalesce(payload->>'country',''),coalesce(payload->>'city',''),coalesce(payload->>'website',''),coalesce(payload->>'description',''),coalesce(payload->>'relationship','participant'),coalesce((payload->>'is_active')::boolean,true)) returning * into result;
 else
  update public.universities u set name=btrim(payload->>'name'),name_kk=coalesce(payload->>'name_kk',''),name_en=coalesce(payload->>'name_en',''),country=coalesce(payload->>'country',''),city=coalesce(payload->>'city',''),website=coalesce(payload->>'website',''),description=coalesce(payload->>'description',''),relationship=coalesce(payload->>'relationship','participant'),is_active=coalesce((payload->>'is_active')::boolean,true)
  where u.id=university_id returning * into result;
  if not found then raise exception 'notFound'; end if;
  update public.events e set university=result.name where e.university_id=result.id;
 end if;
 return to_jsonb(result);
exception when check_violation or not_null_violation or invalid_text_representation then raise exception 'invalidInput';
end $$;
