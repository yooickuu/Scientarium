 name text not null check(length(btrim(name)) between 1 and 300),
 name_key text generated always as (lower(btrim(name))) stored unique,
 name_kk text not null default '' check(length(name_kk)<=300),
 name_en text not null default '' check(length(name_en)<=300),
 country text not null default '' check(length(country)<=300),
 city text not null default '' check(length(city)<=300),
 website text not null default '' check(length(website)<=2000),
 description text not null default '' check(length(description)<=3000),
 relationship text not null default 'participant' check(relationship in ('partner','participant')),
 is_active boolean not null default true,
 created_at timestamptz not null default now()
);
