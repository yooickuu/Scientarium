create table public.profiles (
 id bigint generated by default as identity primary key,
 auth_id uuid not null unique references auth.users(id) on delete cascade,
 email text not null unique,
 full_name text not null default '' check(length(full_name)<=150),
 role text not null default 'user' check(role in ('user','moderator','admin')),
 is_owner boolean not null default false,
 is_active boolean not null default true,
 university text not null default '' check(length(university)<=150),
 specialty text not null default '' check(length(specialty)<=150),
 nickname text unique check(nickname is null or nickname ~ '^[a-z][a-z0-9_]{2,23}$'),
 nickname_changed_at timestamptz,
 avatar_url text not null default '' check(length(avatar_url)<=400000),
 account_category text not null default 'unspecified' check(account_category in ('unspecified','medical_student','postgraduate','researcher','doctor','other')),
 created_at timestamptz not null default now(),
 check(not is_owner or role='admin')
