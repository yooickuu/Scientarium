create function public.record_visit(page_path text,view_key uuid,session_key uuid,device_type text) returns jsonb language plpgsql security definer set search_path='' as $$
declare changed integer; session_digest text=md5(session_key::text); event_number bigint;
begin
 if page_path is null or page_path !~ '^/(calendar|bookmarks|profile|events/[1-9][0-9]*)?$' or session_key is null or view_key is null then raise exception 'invalidInput'; end if;
 if coalesce(scientarium_private.my_role(),'user')<>'user' then return jsonb_build_object('counted',false); end if;
 if page_path like '/events/%' then
  event_number=substring(page_path from 9)::bigint;
  if not exists(select 1 from public.events where id=event_number) then return jsonb_build_object('counted',false); end if;
 end if;
 -- A public telemetry endpoint is approximate, not billing-grade analytics.
 perform pg_advisory_xact_lock(648202);
 if (select count(*) from scientarium_private.visits where created_at>now()-interval '1 minute')>=600
 or (select count(*) from scientarium_private.visits where session_hash=session_digest and created_at>now()-interval '1 minute')>=30 then return jsonb_build_object('counted',false); end if;
 delete from scientarium_private.visits where created_at<now()-interval '90 days';
 insert into scientarium_private.visits(view_id,session_hash,path,day,device)
 values(view_key,session_digest,page_path,(now() at time zone 'Asia/Almaty')::date,case when device_type='mobile' then 'mobile' else 'desktop' end) on conflict(view_id) do nothing;
 get diagnostics changed=row_count;
 if changed=1 and event_number is not null then update public.events set views_count=views_count+1 where id=event_number; end if;
 return jsonb_build_object('counted',changed=1);
end $$;
create function public.admin_stats(period_days integer default 30) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare days integer=case when period_days in (7,30,90) then period_days else 30 end; today date=(now() at time zone 'Asia/Almaty')::date; since date;
begin
 if scientarium_private.my_role() is distinct from 'admin' then raise exception 'forbidden'; end if;
 since=today-days+1;
 return jsonb_build_object(
 'totalEvents',(select count(*) from public.events),'totalUsers',(select count(*) from public.profiles where is_active),
 'upcomingEvents',(select count(*) from public.events where end_date>=now()),'totalViews',(select coalesce(sum(views_count),0) from public.events),
 'pageViews',(select count(*) from scientarium_private.visits where day>=since),'sessions',(select count(distinct session_hash) from scientarium_private.visits where day>=since),
 'mobileViews',(select count(*) from scientarium_private.visits where day>=since and device='mobile'),'days',days,
 'daily',(select jsonb_agg(jsonb_build_object('day',d.day,'views',coalesce(v.views,0),'sessions',coalesce(v.sessions,0)) order by d.day)
 from (select since+i as day from generate_series(0,days-1) as g(i)) d
 left join (select day,count(*) as views,count(distinct session_hash) as sessions from scientarium_private.visits where day>=since group by day) v on v.day=d.day),
 'popularPages',coalesce((select jsonb_agg(to_jsonb(p)) from (select path,count(*) as views from scientarium_private.visits where day>=since group by path order by views desc limit 8)p),'[]'::jsonb));
end $$;

