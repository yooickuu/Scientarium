 specialty text not null default '',
 format text not null default 'offline' check(format in ('offline','online','hybrid')),
 city text not null default '', location text not null, online_url text not null default '',
 start_date timestamptz not null, end_date timestamptz not null,
 description text not null, program text not null default '', speakers text not null default '',
 target_audience text not null default '',
 price_type text not null default 'free' check(price_type in ('free','paid')),
 price text not null default '', registration_url text not null default '', contact_info text not null default '',
